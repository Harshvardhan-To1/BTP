"""Builds results/v2/final_metrics.md from the JSON outputs (no hand-copied numbers)."""
import json, os
R = os.path.join(os.path.dirname(__file__), "..", "results", "v2")
J = lambda n: json.load(open(os.path.join(R, n + ".json")))
out = ["# Final metrics: existing practice vs this work (all simulation, 4-core AVX-512 Xeon)\n", "\"Existing\" = numpy + LAPACK, the standard reference and what the original repo benchmarked (the original repo only covered real random matrices, not complex precoding). Generated by experiments_v2/make_final_metrics.py from results/v2/*.json. Note: in section 3 at 30 km/h our tracker is not better than a cold start (CIs overlap, slightly higher loss).\n"]

k = J("exp17_pipeline_kernel")["rows"]
out += ["## 1. Whole RZF precoder per slot (273 PRBs, complex64): existing numpy+LAPACK vs fused C kernel\n",
        "| K layers, M antennas | existing (numpy + LAPACK) | ours (fused C, 4 thr) | speed-up | fits 0.5 ms slot? (existing -> ours) |", "|---|---|---|---|---|"]
for r in k:
    ex, us = r["numpy_lapack"], r["c_fused_4t"]
    out.append(f"| {r['K']}, {r['M']} | {ex:.2f} ms | {us:.3f} ms | {ex/us:.1f}x | {'yes' if ex<0.5 else 'no'} -> {'yes' if us<0.5 else 'no'} |")

e6 = J("exp6_inversion_accuracy")
out += ["\n## 2. Approximate inversion: matrix multiplies (GEMMs) needed for <= 1% sum-rate loss vs exact\n",
        "| method | " + " | ".join(e6) + " |", "|---|" + "---|" * len(e6)]
names = [n for n in next(iter(e6.values())) if n != "proposed_configs"]
for n in names:
    cells = []
    for pn in e6:
        ok = [x["gemms"] for x in e6[pn][n] if x["rate_loss_pct"] <= 1.0]
        cells.append(f"{min(ok):.0f}" if ok else f">{max(x['gemms'] for x in e6[pn][n]):.0f}")
    out.append(f"| {n} | " + " | ".join(cells) + " |")
e14 = J("exp14_stronger_baselines")
for n in ("Gauss-Seidel", "Block CG (no spectrum info)"):
    cells = []
    for pn in e6:
        d = e14[pn.replace(", ", ",")][n]; ok = [int(g) for g, l in d.items() if l <= 1.0]
        cells.append(f"{min(ok)}" if ok else f">{max(int(g) for g in d)}")
    out.append(f"| {n} (exp14) | " + " | ".join(cells) + " |")
out.append("\nExact Cholesky/LU inverse costs about 1 GEMM-equivalent, so it is cheaper than every row on operation count.")

c = J("exp13_confidence")
out += ["\n## 3. Slot-to-slot tracking, K=16, M=64 (loss vs exact RZF, 95% bootstrap CI over 16 drops)\n",
        "| speed | cold start (6 GEMM) | RMT-WS (ours) |", "|---|---|---|"]
for v in (3, 30, 120):
    a, b = c[f"{v} km/h | cold d0=3,ns=2"], c[f"{v} km/h | Proposed RMT-WS (adaptive)"]
    f = lambda d: f"{d['loss_pct'][0]:.3f}% [{d['loss_pct'][1]:.3f}, {d['loss_pct'][2]:.3f}] at {d['gemms'][0]:.2f} GEMM"
    out.append(f"| {v} km/h | {f(a)} | {f(b)} |")

f10 = J("exp10_fronthaul")["30"]
out += ["\n## 4. Downlink fronthaul, 100 MHz, 64 antennas, 16 layers, BFP-9 IQ\n",
        "| architecture | fronthaul | sum-rate vs exact RZF |", "|---|---|---|",
        f"| existing/default: DU precodes, sends M=64 streams | {f10['catA_M_streams']['fh_gbps']:.1f} Gbit/s | 100% |"]
for bw in (6, 8):
    r = f10[f"Tu=1,bw={bw}"]
    out.append(f"| ours: RU precodes, K=16 layers + {bw}-bit weights every slot | {r['fh_gbps']:.1f} Gbit/s ({100*(1-r['fh_gbps']/f10['catA_M_streams']['fh_gbps']):.0f}% less) | {100*r['rate_ratio']:.1f}% |")

e8 = J("exp8_low_precision"); bits = [4, 5, 6, 8, 10, 12, 16, 24]
sc = "M=64,K=16, AS 12deg, 10 dB"
out += ["\n## 5. Low-precision arithmetic: sum-rate loss vs fp64 exact (K=16, M=64, 10 dB)\n",
        "| mantissa bits | " + " | ".join(map(str, bits[:6])) + " |", "|---|" + "---|" * 6]
for n in e8[sc]:
    out.append(f"| {n} | " + " | ".join(f"{x:.2f}%" for x in e8[sc][n][:6]) + " |")

e9 = J("exp18_fp16_kernel")["sum_rate"]
out += ["\n## 6. Float32 kernel accuracy vs fp64 exact: sum-rate loss <1e-5% in all tested scenarios (K=16/32, up to 30 dB, ill-conditioned).",
        "Rejected optimisation: FP16 weight formation, loss " + ", ".join(f"{v['loss_fp16_pct']:.2f}% ({k})" for k, v in e9.items() if '30 dB' in k) + ", no speed-up.\n"]
open(os.path.join(R, "final_metrics.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
